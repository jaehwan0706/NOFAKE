const path = require('path');
const fs = require('fs');
const { Gateway, Wallets } = require('fabric-network');
(async () => {
  const FABRIC_CONFIG_PATH = path.resolve(process.cwd(), '..', 'fabric-samples', 'test-network', 'organizations', 'peerOrganizations', 'org1.example.com');
  const FABRIC_USER_ID = 'User1@org1.example.com';
  const FABRIC_CHANNEL = 'nofake-channel';
  const FABRIC_CHAINCODE = 'point-cc';
  const wallet = await Wallets.newInMemoryWallet();
  const certDir = path.join(FABRIC_CONFIG_PATH, 'users', FABRIC_USER_ID, 'msp', 'signcerts');
  const keyDir = path.join(FABRIC_CONFIG_PATH, 'users', FABRIC_USER_ID, 'msp', 'keystore');
  console.log({certDir, keyDir, certExists: fs.existsSync(certDir), keyExists: fs.existsSync(keyDir)});
  const certFiles = fs.readdirSync(certDir).filter((name) => name.endsWith('.pem') || name.endsWith('.crt'));
  const keyFiles = fs.readdirSync(keyDir).filter((name) => name.endsWith('.pem') || name.endsWith('.key') || name.endsWith('_sk'));
  console.log('certFiles', certFiles, 'keyFiles', keyFiles);
  const certificate = fs.readFileSync(path.join(certDir, certFiles[0]), 'utf8');
  const privateKey = fs.readFileSync(path.join(keyDir, keyFiles[0]), 'utf8');
  await wallet.put('appUser', { credentials: { certificate, privateKey }, mspId: 'Org1MSP', type: 'X.509' });
  const ccp = JSON.parse(fs.readFileSync(path.join(FABRIC_CONFIG_PATH, 'connection-org1.json'), 'utf8'));
  console.log('ccp peer url', ccp.peers['peer0.org1.example.com'].url);
  const gateway = new Gateway();
  await gateway.connect(ccp, { wallet, identity: 'appUser', discovery: { enabled: true, asLocalhost: true } });
  const network = await gateway.getNetwork(FABRIC_CHANNEL);
  console.log('got network', network.constructor.name);
  const contract = network.getContract(FABRIC_CHAINCODE);
  console.log('got contract', typeof contract.evaluateTransaction);
  const result = await contract.evaluateTransaction('GetBalances', '0x398591b6257b8BA14Baf06728a706a5B73dd2795');
  console.log('GetBalances result', result.toString());
  await gateway.disconnect();
})().catch((e) => { console.error(e); process.exit(1); });
